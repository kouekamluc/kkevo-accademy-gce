def _imp(a, b):
    return (not a) or b


def _iff(a, b):
    return a == b


def _tt(names, cols, gap=" | "):
    """Truth table text. names: variable names; cols: [(label, f)] where f takes the variable values."""
    heads = list(names) + [c[0] for c in cols]
    rows = []
    for vals in itertools.product([True, False], repeat=len(names)):
        cells = ["T" if v else "F" for v in vals] + ["T" if c[1](*vals) else "F" for c in cols]
        rows.append(cells)
    widths = [len(h) for h in heads]
    def fmt(cells):
        parts = [c.center(w).rstrip() if False else c.center(w) for c, w in zip(cells, widths)]
        left = "  ".join(parts[:len(names)])
        right = "  ".join(parts[len(names):])
        return (left + gap + right).rstrip() if cols else left
    out = [fmt(heads), "-" * len(fmt(heads))]
    out += [fmt(r) for r in rows]
    return "\n".join(out)


def _argtt(names, premises, concl):
    """Argument-form table: variables | premises || conclusion, with a mark on any counterexample row."""
    nv, npm = len(names), len(premises)
    heads = list(names) + [lab for lab, _ in premises] + [concl[0]]
    widths = [len(h) for h in heads]
    body = []
    for vals in itertools.product([True, False], repeat=nv):
        ps = [f(*vals) for _, f in premises]
        c = concl[1](*vals)
        cells = ["T" if v else "F" for v in vals] + ["T" if x else "F" for x in ps] + ["T" if c else "F"]
        body.append((cells, all(ps) and not c))
    def fmt(cells, mark=False):
        parts = [x.center(w) for x, w in zip(cells, widths)]
        line = "  ".join(parts[:nv]) + " | " + "  ".join(parts[nv:nv + npm]) + " || " + parts[-1]
        return line + ("   <- counterexample" if mark else "")
    head = fmt(heads)
    return "\n".join([head, "-" * len(head)] + [fmt(c, m) for c, m in body])


