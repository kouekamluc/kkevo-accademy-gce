import random as _random


class _Bag:
    """Gives the position of the correct option so that A-D are used evenly."""

    def __init__(self, seed):
        self.rng = _random.Random(seed)
        self.items = []

    def next(self):
        if not self.items:
            self.items = [0, 1, 2, 3]
            self.rng.shuffle(self.items)
        return self.items.pop()


_BAG = _Bag(11)


