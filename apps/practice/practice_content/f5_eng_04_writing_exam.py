def Q(prompt, right, wrong, pos, concept, skill, hint, expl, fb=""):
    """Multiple-choice question with the correct option placed at index `pos` (0-3).

    `wrong` is a list of three (text, why) pairs; `expl` is a list of (step title, step text) pairs.
    """
    choices = [C(t, why=w) for t, w in wrong]
    choices.insert(pos, C(right, correct=True))
    return MC(prompt, choices, steps=[S(t, text=x) for t, x in expl], concept=concept, skill=skill, hint=hint,
              feedback=fb)


