def ps(module, topic, title, lesson, rows):
    """Build a set of 8 questions. Each row: (prompt, right, [three (wrong, why)], reasoning, concept, skill, hint)."""
    assert len(rows) == 8, (topic, len(rows))
    qs = []
    for i, (prompt, right, wrongs, step, concept, skill, hint) in enumerate(rows):
        assert len(wrongs) == 3
        opts = [C(t, why=w) for t, w in wrongs]
        opts.insert(_PAT[i], C(right, correct=True))
        qs.append(MC(prompt, opts, steps=[S("Reasoning", text=step)], concept=concept, skill=skill, hint=hint, feedback=step))
    return practice_set(module=module, topic=topic, title=title, lesson=lesson, questions=qs)


