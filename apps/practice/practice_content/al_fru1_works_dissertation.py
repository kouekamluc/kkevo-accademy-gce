def mk(prompt, right, wrongs, pos, step, concept, skill, hint, feedback=""):
    """MC helper: `wrongs` = three (text, why) pairs; the right option is inserted at index `pos`."""
    ch = [C(t, why=w) for t, w in wrongs]
    ch.insert(pos, C(right, correct=True))
    return MC(prompt, ch, [S("Reasoning", text=step), S("Answer", text=right)], concept=concept, skill=skill, hint=hint,
              feedback=feedback or step)


