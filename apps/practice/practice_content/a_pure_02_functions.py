def mc(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback, **kw):
    """Multiple choice with the correct option at index `pos` (0 = A) and the three wrong ones in order."""
    choices = [C(t, why=w) for t, w in wrongs]
    choices.insert(pos, C(right, correct=True))
    return MC(prompt, choices, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback, **kw)


