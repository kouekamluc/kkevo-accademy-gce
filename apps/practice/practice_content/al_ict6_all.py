def mc(prompt, correct, wrongs, steps, concept, skill, hint, pos):
    """MC with the correct option at index pos and three (text, why) wrong options."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(correct, correct=True))
    st = [S("Method", text=steps[0]), S("Answer", text=steps[1])]
    return MC(prompt, opts, steps=st, concept=concept, skill=skill, hint=hint,
              feedback="Check the reason for each option in the explanation.")


def nm(prompt, answer, steps, concept, skill, hint, tol=0, unit=""):
    st = [S("Method", text=steps[0]), S("Answer", text=steps[1])]
    return NUM(prompt, answer, steps=st, tolerance=tol, unit=unit, concept=concept, skill=skill, hint=hint,
               feedback="Check the method in the worked steps.")


def build(module, topic, title, lesson, items, offset=0):
    """items: ('mc', prompt, correct, wrongs, steps, concept, skill, hint) or ('num', prompt, answer, steps, concept, skill, hint, tol, unit)."""
    qs, k = [], 0
    for it in items:
        if it[0] == "mc":
            _, prompt, correct, wrongs, steps, concept, skill, hint = it[:8]
            qs.append(mc(prompt, correct, wrongs, steps, concept, skill, hint, (k + offset) % 4))
            k += 1
        else:
            _, prompt, answer, steps, concept, skill, hint, tol, unit = it
            qs.append(nm(prompt, answer, steps, concept, skill, hint, tol, unit))
    assert len(qs) == 8, (title, len(qs))
    return practice_set(module=module, topic=topic, title=title, lesson=lesson, questions=qs)


