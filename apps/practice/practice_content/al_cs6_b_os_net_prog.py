def mcq(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """Multiple choice: the correct option `right` is placed at index `pos` (0 = A ... 3 = D)
    among the three `wrongs` (each a (text, why) pair)."""
    choices = [C(t, why=w) for t, w in wrongs]
    choices.insert(pos, C(right, correct=True))
    return MC(prompt, choices, steps, concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=diagram_alt)


