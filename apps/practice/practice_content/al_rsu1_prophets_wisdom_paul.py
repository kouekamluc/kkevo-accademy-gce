_PAT = [1, 3, 0, 2, 2, 0, 3, 1]
_N = [0]


def q(prompt, right, wrongs, step, concept, skill, hint, feedback=""):
    """4-option MC: `wrongs` = three (text, why) pairs; the correct option position cycles A-D."""
    pos = _PAT[_N[0] % 8]
    _N[0] += 1
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=[S("Reasoning", text=step)], concept=concept, skill=skill, hint=hint,
              feedback=feedback or step)


