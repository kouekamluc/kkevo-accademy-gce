# ---------------------------------------------------------------------- spread the correct option across A-D
def _spread_correct_options():
    """Swap the correct choice into a planned position so that A, B, C and D are used equally (the platform does not shuffle)."""
    base = [0, 1, 2, 3, 2, 3, 0, 1]
    for set_no, practice in enumerate(SETS):
        for n, question in enumerate(practice["questions"]):
            choices = question["choices"]
            current = [k for k, c in enumerate(choices) if c["correct"]][0]
            target = (base[n] + set_no) % 4
            choices[current], choices[target] = choices[target], choices[current]


_spread_correct_options()
