AR = ("Both statements are true and the reason explains the assertion.",
      "Both statements are true but the reason does not explain the assertion.",
      "The assertion is true but the reason is false.",
      "The assertion is false but the reason is true.")


def mc(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback="", diagram="", alt=""):
    """Multiple choice with the correct option inserted at index `pos` (0-3); wrongs = [(text, why), x3]."""
    opts = [C(w, why=y) for w, y in wrongs]
    opts.insert(pos, C(right, correct=True))
    if isinstance(steps, str):
        steps = [S("Reasoning", text=steps)]
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=alt)


def ar(assertion, reason, correct, why3, steps, concept, hint, feedback=""):
    """Assertion-and-reason question. `correct` is 0-3 (index into AR); why3 = reasons for the three wrong options in AR order."""
    opts, k = [], 0
    for i, t in enumerate(AR):
        if i == correct:
            opts.append(C(t, correct=True))
        else:
            opts.append(C(t, why=why3[k])); k += 1
    if isinstance(steps, str):
        steps = [S("Reasoning", text=steps)]
    return MC("Assertion: " + assertion + " Reason: " + reason + " Choose the best answer.", opts, steps=steps,
              concept=concept, skill="Reasoning", hint=hint, feedback=feedback)


def num(prompt, answer, steps, concept, skill, hint, unit="", tolerance=0, diagram="", alt=""):
    return NUM(prompt, answer, steps=steps, concept=concept, skill=skill, hint=hint, unit=unit,
               tolerance=tolerance, diagram=diagram, diagram_alt=alt)


