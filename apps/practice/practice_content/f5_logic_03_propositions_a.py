_SEQ = [2, 0, 3, 1, 3, 1, 0, 2, 1, 3, 2, 0, 0, 2, 1, 3]
_N = [0]


def Q(prompt, options, ci, whys, step, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """Build an MC question: `options` in the order written, `ci` the index of the correct one,
    `whys` the explanations of the wrong options (in order, with or without a blank for the correct one).
    The correct option is then swapped to a rotating position so the answers spread over A-D."""
    whys = list(whys)
    by_index = len(whys) == len(options)
    chs = []
    k = 0
    for i, text in enumerate(options):
        if i == ci:
            chs.append(C(text, correct=True))
        else:
            chs.append(C(text, why=whys[i] if by_index else whys[k]))
            k += 1
    target = _SEQ[_N[0] % len(_SEQ)]
    _N[0] += 1
    chs[ci], chs[target] = chs[target], chs[ci]
    return MC(prompt, chs, steps=[S(t, text=x) for t, x in step], concept=concept, skill=skill, hint=hint,
              feedback=feedback, diagram=diagram, diagram_alt=diagram_alt)


