def Q(prompt, correct, wrongs, right, steps, concept, skill, hint, feedback=""):
    """4-option multiple choice. `correct` goes at 0-based index `right`; `wrongs` = three (text, why) pairs in option order."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(right, C(correct, correct=True))
    st = [S("Answer", text=steps[0])] if len(steps) == 1 else [S(f"Step {n}", text=t) for n, t in enumerate(steps, 1)]
    return MC(prompt, opts, steps=st, concept=concept, skill=skill, hint=hint, feedback=feedback)


