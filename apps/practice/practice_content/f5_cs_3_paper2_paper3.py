def mc(prompt, options, correct, whys, steps, concept, skill, hint, feedback=""):
    """Four options; `whys[i]` explains option i (ignored for the correct one)."""
    choices = [C(t, correct=(i == correct), why=("" if i == correct else whys[i])) for i, t in enumerate(options)]
    return MC(prompt, choices, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback)


