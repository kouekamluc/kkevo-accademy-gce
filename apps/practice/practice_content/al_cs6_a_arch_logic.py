def mc(prompt, right, wrongs, pos, steps, concept, skill, hint, fb="", diagram="", diagram_alt=""):
    """4-option MC. `wrongs` is a list of three (text, why); the right option is placed at index `pos` (0-3)."""
    assert len(wrongs) == 3 and 0 <= pos <= 3
    choices = [C(t, why=w) for t, w in wrongs]
    choices.insert(pos, C(right, correct=True))
    return MC(prompt, choices, steps=steps, concept=concept, skill=skill, hint=hint, feedback=fb,
              diagram=diagram, diagram_alt=diagram_alt)


