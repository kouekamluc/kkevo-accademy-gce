_PAT = [1, 3, 0, 2, 2, 0, 3, 1]
_N = [0]


def q(prompt, right, wrongs, step, concept, skill, hint, steps=None, diagram="", diagram_alt=""):
    """4-option MC. `wrongs` = three (text, why) pairs; the correct option position follows _PAT."""
    pos = _PAT[_N[0] % 8]
    _N[0] += 1
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=steps or [S("Reasoning", text=step)], concept=concept, skill=skill, hint=hint,
              feedback=step, diagram=diagram, diagram_alt=diagram_alt)


def n(prompt, answer, steps, concept, hint, unit="", tolerance=0, skill="Calculation"):
    return NUM(prompt, answer, steps=steps, tolerance=tolerance, unit=unit, concept=concept, skill=skill, hint=hint)


