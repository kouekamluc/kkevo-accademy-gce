def Q(prompt, options, ans, whys, step, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """4-option multiple choice. `ans` is the 0-based index of the correct option; `whys` has one line per option ("" for the right one)."""
    choices = [C(o, correct=(i == ans), why="" if i == ans else whys[i]) for i, o in enumerate(options)]
    return MC(prompt, choices, [S("Reasoning", text=step)], concept=concept, skill=skill, hint=hint,
              feedback=feedback, diagram=diagram, diagram_alt=diagram_alt)


def N(prompt, answer, step, concept, skill, hint, feedback="", math=""):
    return NUM(prompt, answer, [S("Working", math=math, text=step)], concept=concept, skill=skill, hint=hint, feedback=feedback)


