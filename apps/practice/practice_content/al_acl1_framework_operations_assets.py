def n(x):
    assert int(x) == x, x
    s = f"{abs(int(x)):,}".replace(",", " ")
    return "-" + s if x < 0 else s


def m(x):
    return n(x).replace(" ", r"\,")


def vat(net):
    v = _Fr(1925, 10000) * net
    assert v.denominator == 1, net
    return int(v)


def Q(prompt, correct, wrongs, pos, step, hint, concept, skill="Concept", math="", feedback="", diagram="", diagram_alt=""):
    """4-option MC. `wrongs` = 3 (text, why) pairs; the correct option is inserted at index `pos` (0-3)."""
    assert len(wrongs) == 3 and 0 <= pos <= 3 and len(concept) <= 80
    opts = list(wrongs)
    opts.insert(pos, (correct, ""))
    choices = [C(t, correct=(i == pos), why=w) for i, (t, w) in enumerate(opts)]
    return MC(prompt, choices, [S("Reasoning", math=math, text=step)], concept=concept, skill=skill, hint=hint,
              feedback=feedback, diagram=diagram, diagram_alt=diagram_alt)


def N(prompt, answer, step, hint, concept, skill="Calculation", math="", unit="FCFA", feedback="", tolerance=0):
    assert len(concept) <= 80
    return NUM(prompt, answer, [S("Working", math=math, text=step)], concept=concept, skill=skill, hint=hint,
               unit=unit, feedback=feedback, tolerance=tolerance)


