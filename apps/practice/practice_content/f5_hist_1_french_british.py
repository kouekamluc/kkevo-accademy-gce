def q(prompt, options, right, whys, steps, concept, skill, hint):
    """Four-option multiple choice. `right` is the 0-based index; `whys` has one reason per option (the right one is ignored)."""
    # Spread the correct answer over A-D by rotating the options (the platform does not shuffle).
    target = _POSITIONS[len(_COUNT) % len(_POSITIONS)]
    _COUNT.append(1)
    shift = (target - right) % 4
    options = options[-shift:] + options[:-shift] if shift else options
    whys = whys[-shift:] + whys[:-shift] if shift else whys
    right = target
    choices = [C(text, correct=(i == right), why="" if i == right else whys[i]) for i, text in enumerate(options)]
    return MC(prompt, choices, steps=[S(t, text=x) for t, x in steps], concept=concept, skill=skill, hint=hint)


