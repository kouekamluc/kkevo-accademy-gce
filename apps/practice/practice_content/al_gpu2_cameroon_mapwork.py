def q(prompt, right, wrongs, step, concept, skill, hint, diagram="", alt=""):
    """4-option MC. `wrongs` = three (text, why) pairs. `step` is a text or a list of S(...)."""
    pos = _PAT[_N[0] % 8]
    _N[0] += 1
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    steps = [S("Reasoning", text=step)] if isinstance(step, str) else step
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint,
              feedback=step if isinstance(step, str) else "", diagram=diagram, diagram_alt=alt)


def n(prompt, answer, tol, unit, steps, concept, skill, hint, diagram="", alt=""):
    return NUM(prompt, answer, steps=steps, tolerance=tol, unit=unit, concept=concept, skill=skill, hint=hint,
               diagram=diagram, diagram_alt=alt)


