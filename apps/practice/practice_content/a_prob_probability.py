def _mc(prompt, opts, ci, steps, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """opts: four (text, why) pairs; index `ci` is the correct one (its why is ignored)."""
    assert len(opts) == 4 and 0 <= ci < 4
