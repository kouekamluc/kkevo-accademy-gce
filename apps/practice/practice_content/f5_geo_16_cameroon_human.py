def Q(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """Multiple choice with the correct option at index `pos` (0-3); `wrongs` is a list of (text, why)."""
    global _N
    if right not in ("A", "B", "C", "D"):
        pos = _CYCLE[_N % len(_CYCLE)]
        _N += 1
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=diagram_alt)


