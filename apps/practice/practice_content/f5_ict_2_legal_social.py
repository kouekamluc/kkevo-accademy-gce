def mc(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback):
    """Four-option question: `right` is placed at index `pos` (0 = A) among the three `wrongs` (text, why)."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback)


