_N = [0]


def q(prompt, right, wrongs, step, concept, skill, hint):
    """Build a 4-option MC. `wrongs` = three (text, why) pairs; the correct option is placed by a rotating pattern."""
    pos = _PAT[_N[0] % 8]
    _N[0] += 1
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=[S("Reasoning", text=step)], concept=concept, skill=skill, hint=hint, feedback=step)


