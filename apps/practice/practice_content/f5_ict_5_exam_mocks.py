def mk(prompt, opts, ans, wrong, expl, concept, skill, hint):
    """Four-option MC. `opts` are the four option texts, `ans` the index of the correct one,
    `wrong` the three reasons for the wrong options in the order they appear, `expl` a string or list of steps."""
    ws = iter(wrong)
    choices = [C(o, correct=True) if i == ans else C(o, why=next(ws)) for i, o in enumerate(opts)]
    expl = [expl] if isinstance(expl, str) else expl
    steps = [S("Step %d" % (i + 1) if len(expl) > 1 else "Reasoning", text=e) for i, e in enumerate(expl)]
    return MC(prompt, choices, steps, concept=concept, skill=skill, hint=hint)


def num(prompt, answer, expl, concept, skill, hint, tol=0, unit=""):
    expl = [expl] if isinstance(expl, str) else expl
    steps = [S("Step %d" % (i + 1) if len(expl) > 1 else "Working", text=e) for i, e in enumerate(expl)]
    return NUM(prompt, answer, steps, tolerance=tol, unit=unit, concept=concept, skill=skill, hint=hint)


