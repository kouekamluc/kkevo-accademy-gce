# Balanced A-D pattern for the position of the correct option (the platform does not shuffle).
_QPAT = iter("BDACCADBDBCAACDBCBADBADCDACB" * 10)


def Q(prompt, opts, whys, steps, concept, skill, hint, feedback="", diagram="", alt=""):
    """4-option MC. opts[0] is the correct answer; whys: reasons for opts[1], opts[2], opts[3].
    The correct option is moved to the next position of the balanced pattern."""
    assert len(opts) == 4 and len(whys) == 3
    a = "ABCD".index(next(_QPAT))
    pairs = list(zip(opts[1:], whys))
    choices = [C(o, why=w) for o, w in pairs]
    choices.insert(a, C(opts[0], correct=True))
    if isinstance(steps, str):
        steps = [S("Work it out", text=steps)]
    return MC(prompt, choices, steps, concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=alt)


def N(prompt, answer, steps, concept, skill, hint, tol=0, unit="", feedback="", diagram="", alt=""):
    if isinstance(steps, str):
        steps = [S("Work it out", text=steps)]
    return NUM(prompt, answer, steps, tolerance=tol, unit=unit, concept=concept, skill=skill, hint=hint,
               feedback=feedback, diagram=diagram, diagram_alt=alt)

