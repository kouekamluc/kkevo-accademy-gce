_POS = [1, 3, 0, 2, 3, 0, 2, 1]
SETS = []


def _mk(module, topic, title, lesson, items, offset=0):
    qs = []
    for i, it in enumerate(items):
        if it[0] == "NUM":
            _, prompt, ans, tol, unit, expl, concept, skill, hint = it
            qs.append(NUM(prompt, ans, steps=[S("Work it out", text=expl)], tolerance=tol, unit=unit,
                          concept=concept, skill=skill, hint=hint, feedback=expl))
            continue
        prompt, right, wrongs, expl, concept, skill, hint = it
        pos = _POS[(i + offset) % 8]
        cs = [C(w, why=y) for w, y in wrongs]
        cs.insert(pos, C(right, correct=True))
        qs.append(MC(prompt, cs, steps=[S("Reasoning", text=expl)], concept=concept, skill=skill, hint=hint, feedback=expl))
    SETS.append(practice_set(module=module, topic=topic, title=title, lesson=lesson, questions=qs))

