def Q(prompt, correct, wrongs, pos, steps, concept, skill, hint, feedback=""):
    """Four-option MC. `wrongs` is three (text, why) pairs; the correct option is placed at index `pos`."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(correct, correct=True))
    return MC(prompt, opts, steps=[S(a, text=b) for a, b in steps], concept=concept, skill=skill, hint=hint, feedback=feedback)


def N(prompt, answer, steps, concept, skill, hint, feedback="", unit="", tolerance=0):
    return NUM(prompt, answer, steps=[S(a, text=b) for a, b in steps], concept=concept, skill=skill, hint=hint,
               feedback=feedback, unit=unit, tolerance=tolerance)


