def _mc(prompt, correct, wrongs, pos, steps, concept, skill, hint, feedback):
    """Build an MC with the correct option at index `pos` and three (text, why) wrong options."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(correct, correct=True))
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback)


