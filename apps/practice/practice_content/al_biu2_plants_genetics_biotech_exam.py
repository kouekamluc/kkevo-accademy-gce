def Q(prompt, correct, wrongs, sol, c, skill, hint, d="", alt="", pos=None):
    """MC spec. wrongs = [(text, why)] x3; sol = str or [(title, text)]; position balanced by build()."""
    assert len(wrongs) == 3 and all(w[1] for w in wrongs), prompt
    return {"k": "mc", "prompt": prompt, "correct": correct, "wrongs": wrongs, "sol": sol, "c": c, "skill": skill,
            "hint": hint, "d": d, "alt": alt, "pos": pos}


def FQ(prompt, options, ans, whys, sol, c, skill, hint, d="", alt=""):
    """MC with options in fixed order. ans = index; whys = {index: why} for the three wrong ones."""
    assert len(options) == 4 and set(whys) == set(range(4)) - {ans}, prompt
    return {"k": "fq", "prompt": prompt, "options": options, "ans": ans, "whys": whys, "sol": sol, "c": c, "skill": skill,
            "hint": hint, "d": d, "alt": alt, "pos": ans}


def N(prompt, answer, sol, c, skill, hint, tol=0, unit="", d="", alt=""):
    return {"k": "num", "prompt": prompt, "answer": answer, "sol": sol, "c": c, "skill": skill, "hint": hint, "tol": tol,
            "unit": unit, "d": d, "alt": alt}


def _steps(sol):
    if isinstance(sol, str):
        return [S("Solution", text=sol)]
    out = []
    for t in sol:
        out.append(S(t[0], text=t[1]) if len(t) == 2 else S(t[0], math=t[1], text=t[2]))
    return out


def build(specs, seed):
    """MC/NUM questions with the correct option spread evenly over A-D."""
    rng = random.Random(seed)
    counts = [0, 0, 0, 0]
    for s in specs:
        if s["k"] in ("mc", "fq") and s["pos"] is not None:
            counts[s["pos"]] += 1
    out = []
    for s in specs:
        assert s["c"] and len(s["c"]) <= 80, s["c"]
        st = _steps(s["sol"])
        if s["k"] == "num":
            out.append(NUM(s["prompt"], s["answer"], steps=st, tolerance=s["tol"], unit=s["unit"], concept=s["c"],
                           skill=s["skill"], hint=s["hint"], diagram=s["d"], diagram_alt=s["alt"]))
            continue
        if s["k"] == "fq":
            ch = [C(o, correct=(i == s["ans"]), why=s["whys"].get(i, "")) for i, o in enumerate(s["options"])]
        else:
            if s["pos"] is None:
                m = min(counts)
                s["pos"] = rng.choice([i for i in range(4) if counts[i] == m])
                counts[s["pos"]] += 1
            ch = [C(t, why=w) for t, w in s["wrongs"]]
            ch.insert(s["pos"], C(s["correct"], correct=True))
        out.append(MC(s["prompt"], ch, steps=st, concept=s["c"], skill=s["skill"], hint=s["hint"],
                      diagram=s["d"], diagram_alt=s["alt"]))
    return out


