class _Bag:
    def __init__(self, seed):
        self.rng = random.Random(seed)
        self.items = []

    def next(self):
        if not self.items:
            self.items = [0, 1, 2, 3]
            self.rng.shuffle(self.items)
        return self.items.pop()


BAG = _Bag(1)


def use(seed):
    global BAG
    BAG = _Bag(seed)


def Q(prompt, right, wrongs, concept, skill, hint, why, diagram="", diagram_alt=""):
    """MC helper. `wrongs` = three (text, why) pairs; the right option goes to a rotating position."""
    pos = BAG.next()
    wrongs = [(t, y if len(y) >= 30 else y.rstrip(".") + ": this does not match the text or the lesson, so it is not the best answer.")
              for t, y in wrongs]
    opts = [C(t, why=y) for t, y in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=[S("Think it through", text=why), S("Answer", text=right)],
              concept=concept, skill=skill, hint=hint, feedback=why, diagram=diagram, diagram_alt=diagram_alt)


