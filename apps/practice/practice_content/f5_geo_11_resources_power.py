def mq(prompt, right, wrongs, pos, step, concept, skill, hint, diagram="", alt=""):
    """4-option MC: `right` goes at index `pos`; `wrongs` is a list of (text, why) in order."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    return MC(prompt, opts, steps=[S("Answer", text=step)], concept=concept, skill=skill, hint=hint,
              diagram=diagram, diagram_alt=alt)


