def mc(prompt, right, wrongs, pos, steps, concept, skill, hint, feedback="", diagram="", alt=""):
    """Multiple choice with the correct option inserted at index `pos` (0-3); wrongs = [(text, why), x3]."""
    opts = [C(w, why=y) for w, y in wrongs]
    opts.insert(pos, C(right, correct=True))
    if isinstance(steps, str):
        steps = [S("Reasoning", text=steps)]
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=alt)


def num(prompt, answer, steps, concept, skill, hint, unit="", tolerance=0, diagram="", alt=""):
    return NUM(prompt, answer, steps=steps, concept=concept, skill=skill, hint=hint, unit=unit,
               tolerance=tolerance, diagram=diagram, diagram_alt=alt)


