def Q(prompt, options, right, whys, steps, concept, skill, hint, feedback="", diagram="", diagram_alt=""):
    """4-option multiple choice. `right` is the 0-based index of the correct option; `whys[i]` explains wrong option i."""
    return MC(prompt, [C(t, correct=(i == right), why="" if i == right else whys[i]) for i, t in enumerate(options)],
              steps=[S(f"Step {n}", text=t) if len(steps) > 1 else S("Answer", text=t) for n, t in enumerate(steps, 1)],
              concept=concept, skill=skill, hint=hint, feedback=feedback, diagram=diagram, diagram_alt=diagram_alt)


