def mc(pos, prompt, right, wrongs, why_right, concept, skill, hint, diagram="", diagram_alt=""):
    """Four-option question: `right` placed at index `pos`; `wrongs` = three (text, why) pairs."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(pos, C(right, correct=True))
    steps = why_right if isinstance(why_right, list) else [S("Reason", text=why_right)]
    return MC(prompt, opts, steps=steps, concept=concept, skill=skill, hint=hint, diagram=diagram, diagram_alt=diagram_alt)


