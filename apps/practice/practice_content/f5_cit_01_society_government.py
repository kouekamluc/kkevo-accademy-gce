_POSITIONS = [1, 3, 0, 2, 2, 0, 3, 1, 0, 2, 1, 3, 3, 1, 2, 0]
_COUNT = []


def q(prompt, right, wrongs, step, concept, skill, hint, diagram="", diagram_alt=""):
    """Four-option multiple choice. `right` is the correct text; `wrongs` is three (text, why) pairs.
    The correct option is placed at a rotating position so answers spread over A-D."""
    target = _POSITIONS[len(_COUNT) % len(_POSITIONS)]
    _COUNT.append(1)
    opts = [(t, w) for t, w in wrongs]
    opts.insert(target, (right, ""))
    choices = [C(t, correct=(i == target), why=w) for i, (t, w) in enumerate(opts)]
    return MC(prompt, choices, steps=[S("Answer", text=step)], concept=concept, skill=skill, hint=hint,
              diagram=diagram, diagram_alt=diagram_alt)


