def Q(prompt, correct, wrongs, right, steps, concept, skill, hint, feedback="", **kw):
    """4-option multiple choice. `correct` goes at 0-based index `right`; `wrongs` = three (text, why) pairs in option order."""
    opts = [C(t, why=w) for t, w in wrongs]
    opts.insert(right, C(correct, correct=True))
    st = [S("Answer", text=steps[0])] if len(steps) == 1 else [S(f"Step {n}", text=t) for n, t in enumerate(steps, 1)]
    return MC(prompt, opts, steps=st, concept=concept, skill=skill, hint=hint, feedback=feedback, **kw)


def N(prompt, answer, steps, concept, skill, hint, unit="FCFA", tolerance=0):
    return NUM(prompt, answer, steps=[S(f"Step {n}", text=t) for n, t in enumerate(steps, 1)],
               tolerance=tolerance, unit=unit, concept=concept, skill=skill, hint=hint)


