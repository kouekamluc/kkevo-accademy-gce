def _s(steps):
    return [S(t, text=x) for t, x in steps]


def _mc(prompt, right, wrongs, pos, steps, hint, concept, skill, feedback="", diagram="", diagram_alt=""):
    """4-option MC. `wrongs` is a list of (text, why); the correct option goes at index `pos`."""
    ch = [C(t, why=w) for t, w in wrongs]
    ch.insert(pos, C(right, correct=True))
    return MC(prompt, ch, steps=_s(steps), concept=concept, skill=skill, hint=hint, feedback=feedback,
              diagram=diagram, diagram_alt=diagram_alt)


def _num(prompt, answer, steps, hint, concept, skill, feedback=""):
    return NUM(prompt, answer, steps=_s(steps), concept=concept, skill=skill, hint=hint, feedback=feedback)


